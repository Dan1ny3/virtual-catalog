    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        try {
    // Conexiunea cu baza de date
    Class.forName("com.mysql.cj.jdbc.Driver");
    Connection conn = DriverManager.getConnection("jdbc:mysql://localhost:3306/scoala", "root", "1234");
    
    // Interogarea SQL pentru actualizare
    String sql = "UPDATE Nota SET Nume = ?, Clasa = ?, Fizica = ?, Chimie = ?, Matematica = ?, Numaridentificare = ?, Grade = ? WHERE NotaID = ?";
    
    // Calcularea notei finale
    String p = phy.getText();
    double s1 = Double.parseDouble(p);
    String m = math.getText();
    double s2 = Double.parseDouble(m);
    String c = chem.getText();
    double s3 = Double.parseDouble(c);

    double total = (s1 + s2 + s3) / 3;

    String grade;
    if (total >= 8) {
        grade = "Excelent";
    } else if (total >= 7 && total < 8) {
        grade = "Satisfăcător";
    } else if (total >= 6 && total < 7) {
        grade = "Bine";
    } else if (total >= 5 && total < 6) {
        grade = "Insuficient";
    } else {
        grade = "Fail";
    }

    // Pregătirea datelor pentru actualizare
    String n = name.getText();
    String r = roll.getText();  // Numaridentificare
    String cla = cl.getText();
    String ph = phy.getText();
    String mt = math.getText();
    String ch = chem.getText();
    int idNota = Integer.parseInt(id.getText());

    // Utilizarea PreparedStatement pentru a preveni SQL Injection
    PreparedStatement ptst = conn.prepareStatement(sql);
    ptst.setString(1, n);                // Nume
    ptst.setString(2, cla);              // Clasa
    ptst.setInt(3, Integer.parseInt(ph)); // Fizica
    ptst.setInt(4, Integer.parseInt(ch)); // Chimie
    ptst.setInt(5, Integer.parseInt(mt)); // Matematica
    ptst.setString(6, r);                // Numaridentificare
    ptst.setString(7, grade);            // Grade
    ptst.setInt(8, idNota);              // NotaID (pentru WHERE)

    
    // Executarea interogării
    ptst.executeUpdate();

    // Afișarea mesajului de succes
    JOptionPane.showMessageDialog(null, "Datele au fost actualizate cu succes!");

    // Afișarea în zona de text
    text.setText("Note\n\n Student Name: " + n + "\nClass: " + cla + "\n\n-------------------Note\n\nFizica: " + ph +
                 "\nChimie: " + ch + "\nMatematica: " + mt + "\nGrade: " + grade);

    // Închiderea conexiunii
    conn.close();

} catch (Exception e) {
    JOptionPane.showMessageDialog(null, e);
}
   
    }//GEN-LAST:event_jButton1ActionPerformed

