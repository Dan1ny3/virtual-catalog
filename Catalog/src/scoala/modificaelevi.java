    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        
    String id = sid.getText();
    String name = sn.getText();
    String fname = fn.getText();
    String cla = cl.getText();
    String pnum = pn.getText();
    String fnumb = fpn.getText();
    String address = add.getText();
    String rn = roll.getText();

    try {
        Class.forName("com.mysql.cj.jdbc.Driver");
        Connection conn = DriverManager.getConnection("jdbc:mysql://localhost:3306/scoala", "root", "1234");

        // Instrucțiunea SQL corectată cu denumirile corecte ale coloanelor
        String sql = "UPDATE Student SET Nume_tata='" + fname + "', Nume='" + name + "', Clasa='" + cla + "', Telefon='" + pnum + "', Telefontata='" + fnumb + "', Adresa='" + address + "', Rol='" + rn + "' WHERE StudentID='" + id + "'";
        
        PreparedStatement ptst = conn.prepareStatement(sql);
        ptst.executeUpdate();
        
        JOptionPane.showMessageDialog(null, "Modificarile au fost realizate cu succes");
        
        // Închiderea conexiunii
        ptst.close();
        conn.close();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, e);
    }
        
    }//GEN-LAST:event_jButton1ActionPerformed

