    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try{
            
            Class.forName("com.mysql.cj.jdbc.Driver");
            Connection conn= (Connection)DriverManager.getConnection("jdbc:mysql://localhost:3306/scoala","root","1234");
            Statement st=conn.createStatement();
            String sql="select * from Student";
            PreparedStatement ptst= conn.prepareStatement(sql);
            ResultSet rs=ptst.executeQuery();
            DefaultTableModel tm=(DefaultTableModel)studtable.getModel();
            tm.setRowCount(0);
            while(rs.next())
            {
                Object o[]={rs.getInt("StudentID"),rs.getString("Nume"),rs.getString("Nume_tata"),rs.getInt("Telefon"),rs.getInt("Telefontata"),rs.getString("Clasa"),rs.getString("Rol"),rs.getString("Adresa")};
                tm.addRow(o);
            }
            
        }catch(Exception e){
            JOptionPane.showMessageDialog(null, e);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

